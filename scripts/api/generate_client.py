#!/usr/bin/env python3
"""OPS-035: generate the TypeScript client artefacts from the committed spec api/openapi/core.yaml.

  python3 scripts/api/generate_client.py           # (re)write frontend/packages/api-client/src/generated/
  python3 scripts/api/generate_client.py --check   # exit 1 when the committed files differ (CI stage 5)
  pnpm codegen (frontend/) / pnpm turbo run codegen # the same, from the workspace (FEF-014)

Writes ONLY into frontend/packages/api-client/src/generated/ (package.json files belong to FEF-012):
  types.ts     one TS type per component schema + an Operations map (method, path, permission, params, body, response)
               + the Permission union of every authority named in x-required-permission (FEF-014)
  schemas.ts   one Zod schema per component schema + operationSchemas (imports "zod")
  handlers.ts  MSW handlers with deterministic example bodies; msw is passed in (createHandlers({ http, HttpResponse }))
               so this package needs no msw dependency until FEF-014 wires it
  index.ts     re-exports types and schemas (not handlers, so app bundles never pull mocks)
No npm tool and no network: python3 + PyYAML, which CI already has. Deterministic output (sorted), well under the 60 s NFR.
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "api/openapi/core.yaml"
OUT = ROOT / "frontend/packages/api-client/src/generated"
VERBS = ("get", "post", "put", "patch", "delete")
HEADER = "// GENERATED by scripts/api/generate_client.py from api/openapi/core.yaml (OPS-035). Do not edit: rerun the script.\n"


def ref_name(s):
    return s["$ref"].rsplit("/", 1)[-1]


def key(name):
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


# ---------- TypeScript types ----------

def ts(s):
    if not s:
        return "unknown"
    if "$ref" in s:
        return ref_name(s)
    t = s.get("type")
    if "enum" in s:
        out = " | ".join(json.dumps(v) for v in s["enum"])
    elif t == "string":
        out = "string"
    elif t in ("integer", "number"):
        out = "number"
    elif t == "boolean":
        out = "boolean"
    elif t == "array":
        out = f"Array<{ts(s.get('items'))}>"
    elif s.get("properties"):
        req = set(s.get("required") or [])
        out = "{ " + " ".join(f"{key(k)}{'' if k in req else '?'}: {ts(v)};" for k, v in s["properties"].items()) + " }"
    elif isinstance(s.get("additionalProperties"), dict):
        out = f"Record<string, {ts(s['additionalProperties'])}>"
    elif t == "object":
        out = "Record<string, unknown>"
    else:
        out = "unknown"
    return out + (" | null" if s.get("nullable") else "")


# ---------- Zod ----------

def zod(s):
    if not s:
        return "z.unknown()"
    if "$ref" in s:
        return ref_name(s) + "Schema"
    t = s.get("type")
    if "enum" in s and all(isinstance(v, str) for v in s["enum"]):
        out = f"z.enum({json.dumps(s['enum'])})"
    elif t == "string":
        # shortcut: format/pattern are not enforced (Java regex dialect, loose uuid/date strings); add them when a form validates with these
        out = "z.string()"
        if "minLength" in s:
            out += f".min({s['minLength']})"
        if "maxLength" in s:
            out += f".max({s['maxLength']})"
    elif t in ("integer", "number"):
        out = "z.number()" + (".int()" if t == "integer" else "")
        if "minimum" in s:
            out += f".{'gt' if s.get('exclusiveMinimum') is True else 'gte'}({s['minimum']})"
        if "maximum" in s:
            out += f".{'lt' if s.get('exclusiveMaximum') is True else 'lte'}({s['maximum']})"
    elif t == "boolean":
        out = "z.boolean()"
    elif t == "array":
        out = f"z.array({zod(s.get('items'))})"
    elif s.get("properties"):
        req = set(s.get("required") or [])
        out = "z.object({ " + ", ".join(f"{key(k)}: {zod(v)}{'' if k in req else '.optional()'}" for k, v in s["properties"].items()) + " })"
    elif isinstance(s.get("additionalProperties"), dict):
        out = f"z.record(z.string(), {zod(s['additionalProperties'])})"
    elif t == "object":
        out = "z.record(z.string(), z.unknown())"
    else:
        out = "z.unknown()"
    return out + (".nullable()" if s.get("nullable") else "")


# ---------- deterministic examples for MSW ----------

FORMAT_EXAMPLE = {"uuid": "00000000-0000-7000-8000-000000000000", "date": "2026-01-01", "date-time": "2026-01-01T00:00:00Z", "byte": "AA=="}


def example(s, schemas, depth=0):
    if not s:
        return None
    if "$ref" in s:
        return example(schemas[ref_name(s)], schemas, depth + 1)
    if "enum" in s:
        return s["enum"][0]
    t = s.get("type")
    if t == "string":
        v = FORMAT_EXAMPLE.get(s.get("format"), "string")
        return v.ljust(s.get("minLength", 0), "x")
    if t in ("integer", "number"):
        v = s.get("minimum", 0)
        return v + 1 if s.get("exclusiveMinimum") is True else v
    if t == "boolean":
        return False
    if t == "array":
        return [example(s.get("items"), schemas, depth + 1)] if depth < 4 else []  # no schema cycles (topo() checks); this only bounds size
    if s.get("properties"):
        return {k: example(v, schemas, depth + 1) for k, v in s["properties"].items() if not v.get("writeOnly")}
    return {}


# ---------- operations ----------

def content_schema(block):
    for media in (block or {}).get("content", {}).values():
        return media.get("schema")
    return None


def operations(spec):
    ops = []
    for path, item in sorted(spec["paths"].items()):
        for verb in VERBS:
            op = item.get(verb)
            if not op:
                continue
            ok = sorted(c for c in op["responses"] if c.startswith("2"))
            status = ok[0] if ok else "200"
            ops.append({"id": op["operationId"], "verb": verb, "path": path, "permission": op.get("x-required-permission"),
                        "params": op.get("parameters") or [], "body": content_schema(op.get("requestBody")),
                        "status": int(status), "response": content_schema(op["responses"].get(status))})
    return ops


def topo(schemas):
    """Component schemas in dependency order (the spec has no cycles; a cycle would need z.lazy and fails loudly here)."""
    done, out = set(), []

    def deps(s, acc):
        if isinstance(s, dict):
            if "$ref" in s:
                acc.add(ref_name(s))
            for v in s.values():
                deps(v, acc)
        elif isinstance(s, list):
            for v in s:
                deps(v, acc)
        return acc

    def visit(n, stack):
        if n in done:
            return
        if n in stack:
            raise SystemExit(f"schema cycle {' -> '.join(stack + [n])}: emit z.lazy for it")
        for d in sorted(deps(schemas[n], set())):
            visit(d, stack + [n])
        done.add(n)
        out.append(n)

    for n in sorted(schemas):
        visit(n, [])
    return out


def permissions(ops):
    # 'public' / 'authenticated' are not authorities; SpEL such as hasAuthority('setup:edit') or ... keeps only the quoted grants
    return sorted({m for o in ops for m in re.findall(r"[a-z][a-z_]*:[A-Za-z_]+", o["permission"] or "")})


def params_type(params, where):
    ps = [p for p in params if p["in"] == where]
    if not ps:
        return "never"
    return "{ " + " ".join(f"{key(p['name'])}{'' if p.get('required') else '?'}: {ts(p.get('schema'))};" for p in ps) + " }"


def render(spec):
    schemas = spec["components"]["schemas"]
    order = topo(schemas)
    ops = operations(spec)

    types = [HEADER]
    for n in sorted(schemas):
        types.append(f"export type {n} = {ts(schemas[n])};")
    types.append("\nexport type Operations = {")
    for o in ops:
        types.append(f"  {key(o['id'])}: {{ method: {json.dumps(o['verb'])}; path: {json.dumps(o['path'])}; permission: {json.dumps(o['permission'])};"
                     f" pathParams: {params_type(o['params'], 'path')}; query: {params_type(o['params'], 'query')};"
                     f" body: {ts(o['body']) if o['body'] else 'never'}; response: {ts(o['response']) if o['response'] else 'void'} }};")
    types.append("};")
    types.append("export type OperationId = keyof Operations;")
    types.append("\n/** Every authority an operation requires (x-required-permission; `a | b` and SpEL are split). FEF-014: can() takes this. */")
    types.append("export type Permission =\n" + "\n".join(f"  | {json.dumps(p)}" for p in permissions(ops)) + ";")

    zs = [HEADER, 'import { z } from "zod";\n']
    for n in order:
        zs.append(f"export const {n}Schema = {zod(schemas[n])};")
    zs.append("\nexport const operationSchemas = {")
    for o in ops:
        parts = [f"body: {zod(o['body'])}"] if o["body"] else []
        if o["response"]:
            parts.append(f"response: {zod(o['response'])}")
        zs.append(f"  {key(o['id'])}: {{ {', '.join(parts)} }},")
    zs.append("} as const;")

    hs = [HEADER, """// msw is injected (createHandlers({ http, HttpResponse })) so this package compiles without an msw dependency.
type Resolver = () => Response;
type Route<H> = (path: string, resolver: Resolver) => H;
export type MswApi<H> = {
  http: { get: Route<H>; post: Route<H>; put: Route<H>; patch: Route<H>; delete: Route<H> };
  HttpResponse: { json(body: unknown, init?: { status?: number }): Response; new (body: null, init?: { status?: number }): Response };
};

/** One handler per operation in api/openapi/core.yaml, answering its documented 2xx status with a deterministic example body. */
export function createHandlers<H>({ http, HttpResponse }: MswApi<H>, baseUrl = "*"): H[] {
  return ["""]
    for o in ops:
        p = re.sub(r"\{([^}]+)}", r":\1", o["path"])
        if o["status"] == 204 or not o["response"]:
            body = f"new HttpResponse(null, {{ status: {o['status']} }})"
        else:
            body = f"HttpResponse.json({json.dumps(example(o['response'], schemas), separators=(',', ':'))}, {{ status: {o['status']} }})"
        hs.append(f"    http.{o['verb']}(`${{baseUrl}}{p}`, () => {body}), // {o['id']}")
    hs.append("  ];\n}")
    hs.append(f"\nexport const operationCount = {len(ops)};")

    index = HEADER + 'export type * from "./types.ts";\nexport * from "./schemas.ts";\n'
    return {"types.ts": "\n".join(types) + "\n", "schemas.ts": "\n".join(zs) + "\n", "handlers.ts": "\n".join(hs) + "\n", "index.ts": index}


def main(argv):
    # --spec=/--out= let a test generate from a modified copy of the spec into a temp dir (FEF-014 rename proof)
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    spec, out = Path(opt.get("spec", SPEC)), Path(opt.get("out", OUT))
    files = render(yaml.safe_load(spec.read_text()))
    if "--check" in argv:
        stale = [n for n, text in files.items() if not (out / n).exists() or (out / n).read_text() != text]
        if stale:
            print(f"generated client is stale ({', '.join(stale)}): run python3 scripts/api/generate_client.py and commit {OUT.relative_to(ROOT)}")
            return 1
        print(f"generated client up to date ({len(files)} files)")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for n, text in files.items():
        (out / n).write_text(text)
    print(f"wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
