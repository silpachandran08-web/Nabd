// OPS-035: the generated client (packages/api-client/src/generated) matches the spec and its mocks satisfy its own Zod schemas.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHandlers, operationCount } from "../../packages/api-client/src/generated/handlers.ts";
import { operationSchemas, ProblemSchema } from "../../packages/api-client/src/generated/index.ts";

const GEN = new URL("../../packages/api-client/src/generated/", import.meta.url);

// stand-in for msw's http/HttpResponse: records each route and what its resolver answers
function fakeMsw() {
  const routes = [];
  const route = (verb) => (path, resolver) => { routes.push({ verb, path, resolver }); return routes.length; };
  class HttpResponse { constructor(body, init) { this.body = body; this.status = init?.status; } static json(body, init) { return { body, status: init?.status ?? 200 }; } }
  return { routes, api: { http: { get: route("get"), post: route("post"), put: route("put"), patch: route("patch"), delete: route("delete") }, HttpResponse } };
}

test("one MSW handler per spec operation, paths in MSW form under the base URL", () => {
  const { routes, api } = fakeMsw();
  createHandlers(api, "http://localhost:8080");
  const ids = Object.keys(operationSchemas);
  assert.equal(routes.length, operationCount);
  assert.equal(routes.length, ids.length);
  assert.ok(routes.length >= 264, `only ${routes.length} operations`);
  for (const r of routes) {
    assert.ok(r.path.startsWith("http://localhost:8080/"), r.path);
    assert.doesNotMatch(r.path, /[{}]/, `path params must be :name for MSW: ${r.path}`);
  }
  assert.ok(routes.some((r) => r.verb === "post" && r.path.endsWith("/v1/auth/login")));
});

test("every mock body parses with the operation's generated Zod response schema", () => {
  const { routes, api } = fakeMsw();
  createHandlers(api);
  const ids = Object.keys(operationSchemas);
  const bad = [];
  routes.forEach((r, i) => {
    const res = r.resolver();
    const schema = operationSchemas[ids[i]].response;
    if (res.status === 204) { assert.equal(res.body, null); return; }
    if (schema && !schema.safeParse(res.body).success) bad.push(`${ids[i]}: ${JSON.stringify(schema.safeParse(res.body).error.issues[0])}`);
    assert.ok(res.status >= 200 && res.status < 300, `${ids[i]} answers ${res.status}`);
  });
  assert.deepEqual(bad, []);
});

test("Zod schemas enforce the spec: required fields, enums, lengths; Problem+JSON is typed", () => {
  const login = operationSchemas.AuthController_login.body;
  assert.equal(login.safeParse({}).success, false, "an empty login body must fail");
  assert.equal(ProblemSchema.safeParse({ status: 403, title: "Forbidden", errors: [{ field: "x", message: "y" }] }).success, true);
  assert.equal(ProblemSchema.safeParse({ status: "403" }).success, false, "status is an integer");
});

test("generated files carry the do-not-edit header and the Operations map lists the permission", () => {
  for (const f of ["types.ts", "schemas.ts", "handlers.ts", "index.ts"])
    assert.match(readFileSync(new URL(f, GEN), "utf8"), /^\/\/ GENERATED by scripts\/api\/generate_client\.py/);
  const types = readFileSync(new URL("types.ts", GEN), "utf8");
  assert.match(types, /AuthController_login: \{ method: "post"; path: "\/v1\/auth\/login"; permission: "public";/);
  assert.doesNotMatch(readFileSync(new URL("handlers.ts", GEN), "utf8"), /from "msw"/, "msw is injected, not imported");
});
