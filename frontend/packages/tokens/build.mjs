// FEF-022: one source (src/source/*.json) -> dist/tokens.css, custom-media.css, theme.ts, contrast-report.json.
// Exits 1 when a contrast pair is below threshold (the CI gate). Plain Node, no dependencies.
// shortcut: hand-rolled instead of Style Dictionary (not installed, outputs are four small files); swap in when a fifth platform appears.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(here, "src/source", f), "utf8"));
const dark = read("color.dark.json"), light = read("color.light.json"), scale = read("scale.json");
const colorKeys = Object.keys(dark);
for (const k of colorKeys) if (!(k in light)) throw new Error(`light theme lacks ${k}`);
const vars = (o, prefix) => Object.entries(o).filter(([k]) => !k.startsWith("_")).map(([k, v]) => `  --${prefix}${k}: ${v};`);

const css = [
  "/* GENERATED by packages/tokens/build.mjs from src/source/*.json. Do not edit. */",
  ":root {",
  "  color-scheme: dark;",
  ...vars(dark, "nb-"), ...vars(scale.space, "nb-space-"), ...vars(scale.radius, "nb-radius-"), ...vars(scale.fs, "nb-fs-"),
  ...vars(scale.motion, "nb-"), ...vars(scale.layout, "nb-"), ...vars(scale.z, "z-"),
  ...Object.entries(scale.aliases).filter(([k]) => !k.startsWith("_")).map(([k, v]) => `  --${k}: var(--nb-${v});`),
  "}",
  "",
  ':root[data-theme="light"] {',
  "  color-scheme: light; /* FEF-025: native controls and scrollbars follow the theme */",
  ...vars(light, "nb-"),
  "}",
  "",
].join("\n");

const media = "/* GENERATED. Needs postcss-custom-media. */\n" +
  Object.entries(scale.breakpoints).map(([k, v]) => `@custom-media --${k} ${v.query};`).join("\n") + "\n";

const num = (s) => (typeof s === "number" ? s : Number.parseFloat(s));
const asNums = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith("_")).map(([k, v]) => [k, num(v)]));
const rnColors = (c) => Object.fromEntries(Object.entries(c).filter(([k, v]) => !k.startsWith("_") && !/gradient|glow|shadow/.test(k) && !String(v).includes("gradient")));
const theme = {
  colors: { dark: rnColors(dark), light: rnColors(light) },
  space: asNums(scale.space), radius: asNums(scale.radius), fontSize: asNums(scale.fs), zIndex: scale.z,
  breakpoints: Object.fromEntries(Object.entries(scale.breakpoints).map(([k, v]) => [k, v.px])),
  touchMin: num(scale.layout["touch-min"]),
};
const ts = "// GENERATED by packages/tokens/build.mjs. Do not edit.\n" +
  `export const theme = ${JSON.stringify(theme, null, 2)} as const;\nexport type NabdTheme = typeof theme;\n`;

// ---- contrast (WCAG 2.x relative luminance) ----
function parse(c) {
  c = c.trim();
  let m = /^#([0-9a-f]{6})$/i.exec(c);
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)).concat(1);
  m = /^rgba?\(([^)]+)\)$/.exec(c);
  if (m) { const p = m[1].split(",").map((x) => Number.parseFloat(x)); return [p[0], p[1], p[2], p[3] ?? 1]; }
  throw new Error(`cannot parse colour ${c}`);
}
const over = (fg, bg) => [0, 1, 2].map((i) => fg[i] * fg[3] + bg[i] * (1 - fg[3])).concat(1);
const lum = ([r, g, b]) => { const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b); };
function ratio(theme_, fgK, bgK, baseK = "surface-1") {
  const base = parse(theme_[baseK]);
  const bgRaw = parse(theme_[bgK]);
  const bg = bgRaw[3] < 1 ? over(bgRaw, base) : bgRaw;
  const fg = over(parse(theme_[fgK]), bg);
  const [a, b] = [lum(fg), lum(bg)].sort((x, y) => y - x);
  return (a + 0.05) / (b + 0.05);
}
const rows = [];
for (const [name, t] of [["dark", dark], ["light", light]]) {
  for (const [kind, min] of [["text", 4.5], ["ui", 3]]) {
    for (const [fg, bg, base] of scale.contrast[kind]) {
      const r = ratio(t, fg, bg, base);
      rows.push({ theme: name, kind, fg, bg, ...(base && { base }), ratio: Math.round(r * 100) / 100, min, pass: r >= min });
    }
  }
}
const failures = rows.filter((r) => !r.pass);
const report = JSON.stringify({ generated: "packages/tokens/build.mjs", pass: failures.length === 0, failures: failures.length, pairs: rows }, null, 2) + "\n";

const out = process.argv.includes("--check") ? null : join(here, "dist");
const files = { "tokens.css": css, "custom-media.css": media, "theme.ts": ts, "contrast-report.json": report };
if (out) { mkdirSync(out, { recursive: true }); for (const [f, s] of Object.entries(files)) writeFileSync(join(out, f), s); }
else {
  let drift = false;
  for (const [f, s] of Object.entries(files)) { let cur = ""; try { cur = readFileSync(join(here, "dist", f), "utf8"); } catch {} if (cur !== s) { console.error(`dist/${f} is stale: run pnpm --filter @nabd/tokens build`); drift = true; } }
  if (drift) process.exit(1);
}
for (const f of failures) console.error(`contrast FAIL ${f.theme} ${f.fg} on ${f.bg}${f.base ? ` over ${f.base}` : ""}: ${f.ratio} < ${f.min}`);
if (failures.length) process.exit(1);
console.log(`tokens: ${rows.length} contrast pairs ok`);
