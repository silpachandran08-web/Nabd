    var ov = document.getElementById("overlay"), st = S.open && S.byId[S.open];
    var ta = document.getElementById("d-comment"); if (ta) S.draft[S.open] = ta.value;
    var body = document.querySelector(".drawer .db"), scroll = body ? body.scrollTop : 0;
